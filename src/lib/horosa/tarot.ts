export type Drawn = TarotCard & { flipped: boolean; pos: string };

const SPREADS: Record<string, string[]> = {
  three: ["过去", "现在", "建议"],
  five: ["现状", "挑战", "根源", "近未来", "出路"],
};

export function drawSpread(kind: "three" | "five", seed?: number): Drawn[] {
  let s = (seed ?? Date.now()) >>> 0;
  const rnd = () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  const bag = [...DECK];
  for (let i = bag.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [bag[i], bag[j]] = [bag[j], bag[i]];
  }
  const pos = SPREADS[kind];
  return pos.map((p, i) => ({ ...bag[i], flipped: rnd() < 0.42, pos: p }));
}
